"""Golden + structural tests for the src/ -> targets generator."""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def run(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(ROOT / "scripts" / "build-adapters.py"),
                           *args], capture_output=True, text=True, cwd=ROOT)


def test_generate_then_check_is_clean():
    r = run()
    assert r.returncode == 0, r.stderr
    c = run("--check")
    assert c.returncode == 0, c.stdout + c.stderr


def test_instructions_have_applyto_and_header():
    for f in (ROOT / ".github" / "instructions").glob("*.instructions.md"):
        text = f.read_text()
        assert text.startswith("---") and "applyTo:" in text.splitlines()[1], f
        assert "GENERATED BY agentic-os-agi" in text, f


def test_prompt_files_generated_from_commands():
    cmds = {p.stem for p in (ROOT / "src" / "commands").glob("*.md")}
    prompts = {p.name.replace(".prompt.md", "")
               for p in (ROOT / ".github" / "prompts").glob("*.prompt.md")}
    assert cmds == prompts


def test_agent_model_is_string():
    for f in (ROOT / ".github" / "agents").glob("*.agent.md"):
        for line in f.read_text().splitlines():
            if line.startswith("model:"):
                assert not line.split(":", 1)[1].strip().startswith("["), f


def test_mcp_wrappers_match_canonical():
    canon = json.loads((ROOT / "src" / "mcp" / "servers.json").read_text())["servers"]
    canon = {k: {kk: vv for kk, vv in v.items() if not kk.startswith("_")}
             for k, v in canon.items()}
    claude = json.loads((ROOT / ".mcp.json").read_text())["mcpServers"]
    vscode = json.loads((ROOT / ".vscode" / "mcp.json").read_text())["servers"]
    ghub = json.loads((ROOT / ".github" / "mcp.json").read_text())["mcpServers"]
    assert claude == vscode == ghub == canon


def test_skills_copied_to_github():
    src_names = {p.parent.name for p in ROOT.glob("plugins/*/skills/*/SKILL.md")}
    dst_names = {p.parent.name for p in ROOT.glob(".github/skills/*/SKILL.md")}
    assert src_names == dst_names and len(src_names) >= 12


def test_agents_md_contains_definition_of_done():
    text = (ROOT / "AGENTS.md").read_text()
    assert "preflight.sh" in text and "Definition of done" in text
