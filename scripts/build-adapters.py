#!/usr/bin/env python3
"""build-adapters: generate runtime targets from the canonical `src/` layer.

Targets generated (all carry a GENERATED header; edit src/, never the outputs):
  Claude Code : plugins/core-guardrails/commands/* , plugins/core-guardrails/agents/* ,
                .claude/rules/* , .mcp.json
  Copilot     : AGENTS.md , .github/copilot-instructions.md ,
                .github/instructions/*.instructions.md , .github/prompts/*.prompt.md ,
                .github/agents/*.agent.md , .github/skills/* (copy of all plugin skills),
                .github/mcp.json , .vscode/mcp.json , lefthook.yml

Usage: build-adapters.py [--check]   (--check regenerates into a temp tree and diffs;
non-empty diff exits 1 - the CI drift gate).
"""
from __future__ import annotations

import argparse
import difflib
import filecmp
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION = (ROOT / "VERSION").read_text().strip() if (ROOT / "VERSION").exists() else "0.0.0"
HEADER_MD = (f"<!-- GENERATED BY agentic-os-agi build-adapters.py v{VERSION} - DO NOT EDIT."
             " Source: {src} -->\n")


def parse_frontmatter(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---"):
        return {}, text
    lines = text.splitlines()
    fm: dict[str, str] = {}
    end = 0
    for i, line in enumerate(lines[1:], start=1):
        if line.strip() == "---":
            end = i
            break
        if ":" in line:
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"')
    body = "\n".join(lines[end + 1:]).lstrip("\n")
    return fm, body


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


# ------------------------------------------------------------------ generators
def gen_instructions(out: Path) -> None:
    """src/rules/*.md -> .github/instructions/<name>.instructions.md (+ .claude/rules)."""
    repo_wide: list[str] = []
    for rule in sorted((ROOT / "src" / "rules").glob("*.md")):
        fm, body = parse_frontmatter(rule.read_text(encoding="utf-8"))
        apply_to = fm.get("applyTo", "**")
        desc = fm.get("description", rule.stem)
        content = ("---\n"
                   f'applyTo: "{apply_to}"\n'
                   f'description: "{desc} (Agentic OS)"\n'
                   "---\n"
                   + HEADER_MD.format(src=f"src/rules/{rule.name}")
                   + body.rstrip() + "\n")
        write(out / ".github" / "instructions" / f"{rule.stem}.instructions.md", content)
        write(out / ".claude" / "rules" / rule.name,
              HEADER_MD.format(src=f"src/rules/{rule.name}") + body.rstrip() + "\n")
        if fm.get("copilot_repo_wide") == "true":
            repo_wide.append(f"## {desc}\n{body.rstrip()}")
    core = (ROOT / "src" / "agents-instructions.md").read_text(encoding="utf-8")
    write(out / ".github" / "copilot-instructions.md",
          HEADER_MD.format(src="src/agents-instructions.md + src/rules (repo-wide)")
          + core.rstrip() + "\n\n" + "\n\n".join(repo_wide) + "\n")
    write(out / "AGENTS.md",
          HEADER_MD.format(src="src/agents-instructions.md") + core.rstrip() + "\n")


def gen_prompts_and_commands(out: Path) -> None:
    """src/commands/*.md -> Claude plugin commands (pass-through) + Copilot prompt files."""
    for cmd in sorted((ROOT / "src" / "commands").glob("*.md")):
        fm, body = parse_frontmatter(cmd.read_text(encoding="utf-8"))
        desc = fm.get("description", cmd.stem)
        write(out / "plugins" / "core-guardrails" / "commands" / cmd.name,
              f"---\ndescription: {desc}\n---\n"
              + HEADER_MD.format(src=f"src/commands/{cmd.name}") + body.rstrip() + "\n")
        write(out / ".github" / "prompts" / f"{cmd.stem}.prompt.md",
              "---\n"
              f'description: "{desc}"\n'
              "mode: agent\n"
              "---\n"
              + HEADER_MD.format(src=f"src/commands/{cmd.name}") + body.rstrip() + "\n")


def gen_agents(out: Path) -> None:
    """src/agents/*.md -> Claude plugin agents + Copilot .agent.md (model MUST be a string)."""
    for ag in sorted((ROOT / "src" / "agents").glob("*.md")):
        fm, body = parse_frontmatter(ag.read_text(encoding="utf-8"))
        name = fm.get("name", ag.stem)
        desc = fm.get("description", "")
        tools = fm.get("tools", "")
        model = fm.get("model", "")
        if model.startswith("["):
            raise SystemExit(f"build-adapters: {ag} model must be a single string "
                             "(arrays break the Copilot CLI)")
        write(out / "plugins" / "core-guardrails" / "agents" / ag.name,
              f"---\nname: {name}\ndescription: {desc}\ntools: {tools}\nmodel: {model}\n---\n"
              + HEADER_MD.format(src=f"src/agents/{ag.name}") + body.rstrip() + "\n")
        ctools = ", ".join(f"'{t.strip()}'" for t in tools.split(",") if t.strip())
        write(out / ".github" / "agents" / f"{ag.stem}.agent.md",
              "---\n"
              f"name: {name}\n"
              f'description: "{desc}"\n'
              f"tools: [{ctools}]\n"
              "---\n"
              + HEADER_MD.format(src=f"src/agents/{ag.name}") + body.rstrip() + "\n")


def gen_skills(out: Path) -> None:
    """Copy every plugin skill into .github/skills so all Copilot surfaces load them.
    (Copilot also auto-reads .claude/skills; .github/skills covers repos where the plugin
    isn't installed.) SKILL.md is runtime-neutral - no transformation needed."""
    dest = out / ".github" / "skills"
    for skill_md in sorted((ROOT / "plugins").glob("*/skills/*/SKILL.md")):
        sdir = skill_md.parent
        target = dest / sdir.name
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(sdir, target,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))


def gen_mcp(out: Path) -> None:
    src = json.loads((ROOT / "src" / "mcp" / "servers.json").read_text(encoding="utf-8"))
    servers = {k: {kk: vv for kk, vv in v.items() if not kk.startswith("_")}
               for k, v in src.get("servers", {}).items()}
    note = f"GENERATED by build-adapters.py v{VERSION} from src/mcp/servers.json - DO NOT EDIT"
    write(out / ".mcp.json",
          json.dumps({"_generated": note, "mcpServers": servers}, indent=2) + "\n")
    write(out / ".vscode" / "mcp.json",
          json.dumps({"_generated": note, "servers": servers}, indent=2) + "\n")
    write(out / ".github" / "mcp.json",
          json.dumps({"_generated": note, "mcpServers": servers}, indent=2) + "\n")


def gen_lefthook(out: Path) -> None:
    write(out / "lefthook.yml", f"""# GENERATED BY agentic-os-agi build-adapters.py v{VERSION} - DO NOT EDIT.
# Runtime-agnostic enforcement layer: the same attestation the Claude commit-integrity hook
# verifies, wired as native git hooks so GitHub Copilot (any surface) and plain git hit the
# same bar. Bypassable locally with --no-verify by design; the server-side backstop is the
# jj-preflight required status check + repository ruleset.
pre-commit:
  parallel: false
  commands:
    commit-integrity:
      run: bash scripts/verify-attestation.sh --staged
pre-push:
  commands:
    commit-integrity:
      run: bash scripts/verify-attestation.sh --require-fresh
""")


GENERATORS = [gen_instructions, gen_prompts_and_commands, gen_agents, gen_skills,
              gen_mcp, gen_lefthook]

GENERATED_PATHS = ["AGENTS.md", "lefthook.yml", ".mcp.json", ".vscode/mcp.json",
                   ".claude/rules", ".github/copilot-instructions.md",
                   ".github/instructions", ".github/prompts", ".github/agents",
                   ".github/skills", ".github/mcp.json",
                   "plugins/core-guardrails/commands", "plugins/core-guardrails/agents"]


def diff_tree(a: Path, b: Path) -> list[str]:
    diffs: list[str] = []
    for rel in GENERATED_PATHS:
        pa, pb = a / rel, b / rel
        if pa.is_file() or pb.is_file():
            if not pa.exists() or not pb.exists() or not filecmp.cmp(pa, pb, shallow=False):
                diffs.append(rel)
            continue
        fa = {p.relative_to(pa) for p in pa.rglob("*") if p.is_file()} if pa.exists() else set()
        fb = {p.relative_to(pb) for p in pb.rglob("*") if p.is_file()} if pb.exists() else set()
        for f in sorted(fa | fb):
            if f not in fa or f not in fb or not filecmp.cmp(pa / f, pb / f, shallow=False):
                diffs.append(f"{rel}/{f}")
    return diffs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify generated files are up to date (CI drift gate)")
    args = ap.parse_args()

    if args.check:
        import tempfile
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            # skills copy needs plugins/ present relative to out only at diff time;
            # generate into tmp, then compare against the repo.
            for gen in GENERATORS:
                gen(out)
            drift = diff_tree(ROOT, out)
            if drift:
                print("build-adapters --check: DRIFT in generated files:")
                for d in drift:
                    print(f"  - {d}")
                print("Run scripts/build-adapters.py and commit the result.")
                return 1
            print("build-adapters --check: generated files are up to date.")
            return 0

    for gen in GENERATORS:
        gen(ROOT)
    print(f"build-adapters: generated Claude + Copilot targets (v{VERSION}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
